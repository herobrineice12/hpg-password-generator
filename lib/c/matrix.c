static const uint32_t CONSTANT = 0x9e3779b9;
static const uint32_t MAX_SIZE = 256;
static const uint32_t INDEX_LIMIT = 15;

typedef struct Matrix {
  uint32_t data[256];
  uint32_t constant;
} Matrix;

uint32_t collect(Matrix *matrix, uint32_t row, uint32_t column) {
  if (row > INDEX_LIMIT || column > INDEX_LIMIT) {
    row &= 0xF;
    column &= 0xF;
  }

  return matrix->data[row * 16 + column];
}

uint32_t collect_inclusive_disjunction_column(Matrix *matrix, uint32_t row) {
  uint32_t buffer = 0;
  uint32_t ceil = (INDEX_LIMIT + 1) >> 1;

  for (int i = 0; i < ceil; i++) {
    buffer ^= collect(matrix, row, i * 2);
  }

  return buffer;
}

int write(Matrix *matrix, uint32_t row, uint32_t column, uint32_t value) {
  if (row > INDEX_LIMIT || column > INDEX_LIMIT)
    return 0;
  matrix->data[row * 16 + column] = value;
  return 1;
}

Matrix *fill(Matrix *mantis, const uint32_t *array, uint32_t length) {
  *mantis = (Matrix){.constant = CONSTANT, .data = {0}};

  if (length > MAX_SIZE) {
    length = MAX_SIZE;
  }

  uint32_t *write_pointer = mantis->data;

  memmove(write_pointer, array, length);

  if (length < MAX_SIZE) {
    write_pointer += length;
    length = MAX_SIZE - length;
    memmove(write_pointer, padding_buffer, length);
  }

  return mantis;
}
